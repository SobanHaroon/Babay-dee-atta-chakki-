import {readFile,mkdir,writeFile} from 'node:fs/promises';
import {pathToFileURL} from 'node:url';
import {resolve} from 'node:path';
export const commerceMigrations=['scripts/20261002_catalog_access.sql','scripts/20261002_secure_commerce.sql','scripts/20261011_confirm_kg_catalog.sql','scripts/20261014_order_dashboard.sql'];
export const commerceSetupFile='supabase/checkout-setup.sql';
export async function commerceMigrationSql(){
 const sections=[];
 for(const file of commerceMigrations){
  const sql=(await readFile(file,'utf8')).replace(/^\uFEFF/,'').replace(/\r\n/g,'\n');
  if((sql.match(/^begin;$/gm)||[]).length!==1||(sql.match(/^commit;$/gm)||[]).length!==1)throw Error('Unexpected migration transaction boundaries: '+file);
  sections.push('-- Source: '+file+'\n'+sql.replace(/^(?:begin|commit);\n?/gm,''));
 }
 return '-- Generated by npm run db:bundle. Do not edit this copy.\n-- Test in staging first. Run in Supabase SQL Editor as the trusted database owner.\n-- Installs checkout storage, access restrictions and owner-confirmed kg stock metadata.\n-- Does not create customer orders or send notifications. Does not change product prices.\n-- All setup changes are atomic; an error rolls the entire setup back.\nbegin;\nselect pg_advisory_xact_lock(20261012,1);\n\n'+sections.join('\n\n')+'\ncommit;\n';
}
if(process.argv[1]&&import.meta.url===pathToFileURL(resolve(process.argv[1])).href){
 await mkdir('supabase',{recursive:true});await writeFile(commerceSetupFile,await commerceMigrationSql());
 console.log('Created '+commerceSetupFile+'. No database connection or changes were made.');
}
