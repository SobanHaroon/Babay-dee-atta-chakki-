import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {randomUUID} from 'node:crypto';
import {PGlite} from '@electric-sql/pglite';
import {commerceMigrationSql,commerceSetupFile} from './build-commerce-migration.mjs';
import {checkout,authorizeOrder,databaseCommerceRepository} from '../api/commerce.js';
import {normalizeCatalog} from '../api/catalog.js';
import {upcomingDeliveryDays} from '../src/lib/commerce.js';

process.env.ORDER_ACCESS_SECRET='synthetic-postgres-test-secret-at-least-32-characters';

test('real PostgreSQL migrations, checkout persistence, atomic stock, retries and table isolation', async t=>{
 const db=new PGlite();
 const query=(sql:string,args:any[]=[])=>db.query<any>(sql,args);
 const scalar=async(sql:string,args:any[]=[])=>Object.values((await query(sql,args)).rows[0])[0];
 try{
  await db.exec(`create role anon;create role authenticated;create role service_role bypassrls;
    create table products(id bigint primary key,"product name" text,price text,quantity text);
    create table orders(id bigint generated by default as identity primary key,created_at timestamptz not null default now(),
    "order id" integer,"customer name" text,"contact number" text,"customer address" text,date date,time timetz,
    "Price" numeric,"Delivery charges" numeric,"Order pricing" numeric,"delivery latitude" double precision,"delivery longitude" double precision,"Order status" text);
    create table delivery_location(id bigint primary key,address text);
    grant select on delivery_location to anon;
    insert into products values(1,'Synthetic Atta','180','100000'),(2,'Synthetic Besan','380','0'),(3,'Synthetic Pack','500','2');`);
  await t.test('a failed setup rolls back all schema changes and preserves original products',async()=>{
   await query("insert into products values(99,'Invalid Synthetic Inventory','180','100000000000')");
   await assert.rejects(db.exec(await commerceMigrationSql()),(e:any)=>e.code==='23514');
   await db.exec('rollback');
   assert.equal(await scalar("select to_regclass('public.secure_orders')"),null);
   assert.equal(await scalar("select count(*)::int from information_schema.columns where table_schema='public' and table_name='products' and column_name='stock_quantity'"),0);
   assert.equal(await scalar("select quantity from products where id=1"),'100000');
   await query('delete from products where id=99');
  });
  const setupSql=await commerceMigrationSql();
  assert.equal((await readFile(commerceSetupFile,'utf8')).replace(/\r\n/g,'\n'),setupSql);
  await db.exec(setupSql);
  await t.test('legacy stock backfill has the confirmed scale, preserves zero and supports future pack metadata',async()=>{
   assert.equal(await scalar('select stock_quantity::float8 from products where id=1'),10000);
   assert.equal(await scalar('select stock_quantity::float8 from products where id=2'),0);
   await query("update products set sale_unit='pack',stock_quantity=2,pack_weight_kg=1 where id=3");
  });
  const client={
   from(table:string){return {select(_columns:string){let field='',value:any;return {eq(f:string,v:any){field=f;value=v;return this;},maybeSingle(){return this;},async abortSignal(){
    assert.equal(table,'secure_orders');assert.ok(['checkout_context','id'].includes(field));
    return {data:(await query(`select * from secure_orders where ${field}=$1`,[value])).rows[0]||null,error:null};
   }};}};},
   rpc(name:string,args:any){return {async abortSignal(){assert.equal(name,'place_store_order');try{return {data:await scalar('select place_store_order($1::jsonb)',[JSON.stringify(args.p_order)]),error:null};}catch(e:any){return {data:null,error:{code:e.code,message:e.message}};}}};}
  };
  const repository=databaseCommerceRepository(client);
  const deps={repository,catalog:async()=>normalizeCatalog((await query('select * from products')).rows),quote:async()=>{throw Error('Pickup fixture must not request a route');}};
  const input=()=>({checkoutContext:randomUUID(),addressVersion:1,fulfillmentType:'pickup',name:'Synthetic Customer',phone:'03000000000',deliveryDate:upcomingDeliveryDays()[0].value,deliverySlot:'Morning',cartItems:[{id:'1',quantity:1.5,price:.01}],total:.01,discount:500,paymentStatus:'paid'});
  const body=input();let order:any;
  await db.exec('set role service_role');
  await t.test('checkout uses actual SQL, rebuilds totals, persists unpaid state and deducts kilograms',async()=>{
   order=await checkout(body,body.checkoutContext,deps);
   assert.equal(order.order.total,270);assert.equal(order.order.discount,0);assert.equal(order.order.paymentStatus,'unpaid');
   assert.equal(await scalar('select stock_quantity::float8 from products where id=1'),9998.5);
   assert.equal(Number(await scalar('select quantity from products where id=1')),99985);
   assert.equal(await scalar('select count(*)::int from secure_orders'),1);
   assert.equal((await authorizeOrder(repository,order.orderId,order.orderAccessToken)).id,order.orderId);
   await assert.rejects(authorizeOrder(repository,order.orderId,'x'.repeat(43)),/could not be verified/);
  });
  await t.test('retries produce one order and one inventory deduction',async()=>{
   const results=await Promise.all(Array.from({length:4},()=>checkout(body,body.checkoutContext,deps)));
   assert.ok(results.every(r=>r.orderId===order.orderId&&!r.created));
   assert.equal(await scalar('select count(*)::int from secure_orders'),1);
   const persisted=(await repository.findOrder(order.orderId))!;
   const rpcRetries=await Promise.all(Array.from({length:4},()=>repository.place(persisted)));
   assert.ok(rpcRetries.every(r=>r.record.id===order.orderId&&!r.created));
   await assert.rejects(repository.place({...persisted,request_hash:'f'.repeat(64)}),(e:any)=>e.code==='IDEMPOTENCY_CONFLICT');
   assert.equal(await scalar('select stock_quantity::float8 from products where id=1'),9998.5);
   await assert.rejects(checkout({...body,name:'Other Synthetic Customer'},body.checkoutContext,deps),(e:any)=>e.code==='IDEMPOTENCY_CONFLICT');
  });
  await t.test('dashboard columns, original address and legacy metadata match the existing format',async()=>{
   const legacy=(await query('select * from orders')).rows[0];
   assert.equal(legacy['customer name'],body.name);assert.equal(legacy['contact number'],body.phone);
   assert.equal(Number(legacy.Price),270);assert.equal(Number(legacy['Order pricing']),270);assert.equal(Number(legacy['Delivery charges']),0);
   assert.equal(legacy['Order status'],'order placed');
   const meta=JSON.parse(legacy['customer address'].split(' | METADATA:')[1]);
   assert.equal(meta.secureOrderId,order.orderId);assert.equal(meta.items[0].quantity,1.5);assert.equal(meta.items[0].unit,'Kg');
   assert.ok(!('orderAccessToken' in meta));
   assert.equal(await scalar('select count(*)::int from staff_notification_outbox'),1);
   assert.equal(await scalar('select project_order_to_dashboard($1)',[order.orderId]),legacy['order id']);
   assert.equal(await scalar('select count(*)::int from orders'),1);
   await query('update orders set "Order status"=$1 where id=$2',['Delivered',legacy.id]);
   assert.equal((await repository.findOrder(order.orderId))!.document.status,'Delivered');
  });
  await t.test('notification leases, retry delay, acknowledgements and private payload are enforced',async()=>{
   const job:any=await scalar('select claim_staff_notification($1)',[order.orderId]);
   assert.equal(job.orderId,order.orderId);assert.equal(job.total,270);
   assert.doesNotMatch(JSON.stringify(job),/Synthetic Customer|03000000000|order_access_hash/);
   assert.equal(await scalar('select claim_staff_notification($1)',[order.orderId]),null);
   assert.equal(await scalar('select finish_staff_notification($1,$2,null)',[order.orderId,randomUUID()]),false);
   assert.equal(await scalar('select finish_staff_notification($1,$2,$3)',[order.orderId,job.leaseToken,'NTFY_HTTP_429']),true);
   assert.equal(await scalar('select claim_staff_notification($1)',[order.orderId]),null);
   await query("update staff_notification_outbox set next_attempt_at=now()-interval '1 minute'");
   const retry:any=await scalar('select claim_staff_notification($1)',[order.orderId]);assert.notEqual(retry.leaseToken,job.leaseToken);
   assert.equal(await scalar('select finish_staff_notification($1,$2,null)',[order.orderId,retry.leaseToken]),true);
   assert.equal(await scalar('select claim_staff_notification($1)',[order.orderId]),null);
  });
  const record=async(items:any[])=>({...(await repository.findOrder(order.orderId))!,id:'BDEC-'+randomUUID().replaceAll('-',''),checkout_context:randomUUID(),document:{...order.order,items}});
  await t.test('stock change in a later bundle item rolls back every deduction and order insert',async()=>{
   const r=await record([{id:'1',quantity:2,price:180},{id:'2',quantity:1,price:380}]);
   await assert.rejects(repository.place(r),(e:any)=>e.code==='STOCK_CHANGED');
   assert.equal(await scalar('select stock_quantity::float8 from products where id=1'),9998.5);
   assert.equal(await scalar('select count(*)::int from secure_orders'),1);
  });
  await t.test('database rejects stale prices, absent quantity and fractional packs without changing stock',async()=>{
   for(const [item,code] of [[{id:'1',quantity:1,price:1},'PRICE_CHANGED'],[{id:'1',price:180},'STOCK_CHANGED'],[{id:'3',quantity:.5,price:500},'STOCK_CHANGED'],[{id:'1',quantity:.15,price:180},'STOCK_CHANGED']] as const){
    await assert.rejects(repository.place(await record([item])),(e:any)=>e.code===code);
   }
   assert.equal(await scalar('select count(*)::int from secure_orders'),1);
  });
  await t.test('dashboard insert failure rolls back secure order, stock and notification together',async()=>{
   await db.exec('reset role');
   await db.exec('alter table orders add constraint synthetic_rejection check ("Price"<300)');
   await db.exec('set role service_role');
   const failed=await record([{id:'1',quantity:2,price:180}]);
   await assert.rejects(repository.place(failed));
   assert.equal(await scalar('select count(*)::int from secure_orders'),1);assert.equal(await scalar('select count(*)::int from orders'),1);
   assert.equal(await scalar('select count(*)::int from staff_notification_outbox'),1);
   assert.equal(await scalar('select stock_quantity::float8 from products where id=1'),9998.5);
   await db.exec('reset role');await db.exec('alter table orders drop constraint synthetic_rejection');await db.exec('set role service_role');
  });
  await t.test('inventory edits synchronize in both directions and conflicting changes are rejected',async()=>{
   await query("update products set quantity='150' where id=2");assert.equal(await scalar('select stock_quantity::float8 from products where id=2'),15);
   await query('update products set stock_quantity=12.5 where id=2');assert.equal(Number(await scalar('select quantity from products where id=2')),125);
   await assert.rejects(query("update products set quantity='200',stock_quantity=19 where id=2"),/CONFLICTING_INVENTORY/);
   await assert.rejects(query("update products set quantity='garbage' where id=2"),/INVALID_INVENTORY/);
  });
  await t.test('database receipt claims and shared request limits are enforced',async()=>{
   assert.equal(await scalar('select claim_order_receipt($1)',[order.orderId]),true);
   assert.equal(await scalar('select claim_order_receipt($1)',[order.orderId]),false);
   for(let i=0;i<3;i++)assert.equal((await scalar("select consume_api_rate_limit('synthetic',2,60)") as any).allowed,i<2);
  });
  await db.exec('reset role');
  await t.test('repeat migrations preserve orders and already-decremented stock',async()=>{
   const setupSql=await commerceMigrationSql();
  assert.equal((await readFile(commerceSetupFile,'utf8')).replace(/\r\n/g,'\n'),setupSql);
  await db.exec(setupSql);
   assert.equal(await scalar('select stock_quantity::float8 from products where id=1'),9998.5);
   assert.equal(await scalar('select count(*)::int from secure_orders'),1);
  });
  await t.test('the exact owner repair file restores a pre-bridge order once without a second stock deduction',async()=>{
   const old=await record([{id:'1',quantity:1.5,price:180}]);old.id='BDEC-4ffb08f183424cbdb554fb91efdc986e';old.document.id=old.id;
   await db.exec('alter table secure_orders disable trigger secure_order_dashboard');
   await query('insert into secure_orders(id,document,checkout_context,idempotency_key,request_hash,order_access_hash,access_expires_at) values($1,$2,$3,$4,$5,$6,$7)',[old.id,JSON.stringify(old.document),old.checkout_context,old.idempotency_key,old.request_hash,old.order_access_hash,old.access_expires_at]);
   await db.exec('alter table secure_orders enable trigger secure_order_dashboard');
   const repair=await readFile('supabase/order-dashboard-repair.sql','utf8');
   await db.exec(repair);await db.exec(repair);
   assert.equal(await scalar('select count(*)::int from orders'),2);
   assert.equal(await scalar('select count(*)::int from staff_notification_outbox'),2);
   assert.equal(await scalar('select count(*)::int from secure_orders'),2);
   assert.equal(await scalar('select stock_quantity::float8 from products where id=1'),9998.5);
  });
  await t.test('anonymous and authenticated roles cannot read customer data, mutate catalog or call order RPCs',async()=>{
   for(const role of ['anon','authenticated']){
    await db.exec(`set role ${role}`);
    for(const sql of ['select * from orders','select * from order_dashboard_links','select * from staff_notification_outbox',"select project_order_to_dashboard('x')","select claim_staff_notification(null)","select place_store_order('{}'::jsonb)",'select * from secure_orders','select * from delivery_location','select * from customer_reviews','update products set price=\'1\'','delete from products',"select place_secure_order('{}'::jsonb)","select claim_order_receipt('id')","select consume_api_rate_limit('key',1,60)"]){await assert.rejects(query(sql),(e:any)=>e.code==='42501');}
    await db.exec('reset role');
   }
  });
 }finally{await db.close();}
});
